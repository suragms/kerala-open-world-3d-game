async(page)=>{
  const results=[],check=(value,message)=>{if(!value)throw new Error(message);results.push({name:message,passed:true});};
  const state=()=>page.evaluate(()=>window.__KOW__.snapshot());
  await page.getByRole('button',{name:'Pause game',exact:true}).click();await page.getByRole('button',{name:'Return to arrival point',exact:false}).click();
  await page.getByRole('button',{name:'Mouse movement',exact:true}).click();
  check(await page.getByRole('button',{name:'Stop moving',exact:true}).isVisible(),'Mouse Stop remains available while idle');
  await page.mouse.move(720,400);await page.locator('.interact-prompt').click();await page.waitForTimeout(250);
  check((await state()).driving,'Enter vehicle with mouse');
  const pedal=await page.getByRole('button',{name:'Drive forward',exact:true}).boundingBox();
  await page.mouse.move(pedal.x+pedal.width/2,pedal.y+pedal.height/2);await page.mouse.down();
  await page.mouse.move(1000,450,{steps:8});await page.waitForTimeout(450);
  check(Math.abs((await state()).steering)>.08,'Captured pedal movement still steers');await page.mouse.up();
  await page.mouse.move(720,400);await page.mouse.down({button:'right'});await page.waitForTimeout(800);await page.mouse.up({button:'right'});
  await page.keyboard.down('ArrowUp');await page.waitForTimeout(700);
  check((await state()).speed>3 && (await state()).inputDevice==='keyboard','Keyboard throttle takes over while Mouse movement remains selected');await page.keyboard.up('ArrowUp');
  await page.locator('.interact-prompt').click();await page.waitForTimeout(1400);check(!(await state()).driving,'Exit after mixed input safely');
  await page.getByRole('button',{name:'Open world map',exact:true}).first().click();
  await page.getByRole('textbox',{name:'Search places',exact:true}).fill('Thrissur KSRTC Bus Station');
  await page.getByRole('button',{name:'Bus stations',exact:true}).click();await page.locator('.search-results .place-result').first().click();await page.getByRole('button',{name:'Explore this location',exact:true}).click();
  await page.waitForFunction(()=>window.__KOW__?.diagnostics().area==='station-thrissur');
  await page.getByRole('button',{name:'Open world map',exact:true}).first().click();
  await page.getByRole('textbox',{name:'Search places',exact:true}).fill('Guruvayur KSRTC');
  await page.getByRole('button',{name:'Bus stations',exact:true}).click();await page.locator('.search-results .place-result').first().click();
  await page.getByLabel('Route transport mode',{exact:true}).selectOption('road');
  await page.getByTestId('network-route').waitFor();
  const path=await page.getByTestId('network-route').getAttribute('points');
  check(path.trim().split(' ').length>10,'Road preview contains the imported bends');
  await page.screenshot({path:'phase10-network-route.png'});
  await page.getByLabel('Route transport mode',{exact:true}).selectOption('air');
  await page.waitForFunction(()=>document.querySelector('.map-selection')?.textContent.includes('straight-line'));
  check(await page.getByTestId('network-route').count()===0,'Air transfer has no fabricated road preview');
  check(/straight-line/i.test(await page.locator('.map-selection').innerText()),'Air distance is labelled straight-line');
  await page.getByLabel('Route transport mode',{exact:true}).selectOption('rail');
  await page.waitForFunction(()=>/imported rail|Route unavailable/.test(document.querySelector('.map-selection')?.textContent??''));
  const railText=await page.locator('.map-selection').innerText();
  check(/imported rail|Route unavailable/i.test(railText),'Rail mode uses rail geometry or clearly rejects missing coverage');
  if(/Route unavailable/i.test(railText))check(await page.getByTestId('network-route').count()===0,'Unavailable rail does not retain the road preview');
  await page.getByRole('button',{name:'Close world map',exact:true}).click();
  await page.getByRole('button',{name:'Open settings',exact:true}).click();await page.getByRole('button',{name:'World & display',exact:true}).click();
  await page.getByRole('checkbox',{name:'Adaptive resolution',exact:true}).uncheck();
  await page.getByLabel('Weather',{exact:true}).selectOption('monsoon');await page.getByLabel('Time of day',{exact:true}).selectOption('night');
  await page.getByRole('button',{name:'Done',exact:false}).click();await page.waitForTimeout(300);
  check(await page.evaluate(()=>window.__KOW__.perf().resolutionScale)===1,'Adaptive resolution can be disabled');
  await page.screenshot({path:'phase10-monsoon-night.png'});
  const traffic=await page.evaluate(()=>window.__KOW__.controls().traffic);
  check(traffic.length>0&&traffic.every(a=>Number.isFinite(a.position.x)&&!a.blocked),'Traffic remains outside static blocked footprints');
  check(traffic.some(a=>['Truck','Delivery van','Tourist van'].includes(a.kind)),'Utility traffic models are active');
  return {results,traffic,railText,perf:await page.evaluate(()=>window.__KOW__.perf())};
}
